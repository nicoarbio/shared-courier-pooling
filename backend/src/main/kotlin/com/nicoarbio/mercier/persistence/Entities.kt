package com.nicoarbio.mercier.persistence

import com.nicoarbio.mercier.domain.StopKind
import jakarta.persistence.CollectionTable
import jakarta.persistence.Column
import jakarta.persistence.ElementCollection
import jakarta.persistence.Embeddable
import jakarta.persistence.Entity
import jakarta.persistence.EnumType
import jakarta.persistence.Enumerated
import jakarta.persistence.FetchType
import jakarta.persistence.Id
import jakarta.persistence.JoinColumn
import jakarta.persistence.ManyToOne
import jakarta.persistence.MapKeyColumn
import jakarta.persistence.OrderColumn
import jakarta.persistence.Table
import java.math.BigDecimal
import java.time.Instant
import java.time.LocalDateTime
import java.util.UUID

/*
 * JPA entities, kept apart from the domain model (see Mappers.kt): the engine never depends on persistence.
 *
 * Ids are generated by the application (UUID) before persisting, so equals/hashCode can rely on the id alone
 * and stay stable across the entity lifecycle. toString never walks relations, to avoid triggering lazy loads.
 */

@Entity
@Table(name = "merchant")
class MerchantEntity(
	@Id val id: UUID,
	var name: String,
	var lon: Double,
	var lat: Double,
) {
	override fun equals(other: Any?) = other is MerchantEntity && other.id == id
	override fun hashCode() = id.hashCode()
	override fun toString() = "MerchantEntity(id=$id, name=$name)"
}

enum class OrderStatus { PENDING, PLANNED }

@Entity
@Table(name = "delivery_order")
class OrderEntity(
	@Id val id: UUID,
	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "merchant_id")
	val merchant: MerchantEntity,
	@Column(name = "dest_lon") val destLon: Double,
	@Column(name = "dest_lat") val destLat: Double,
	val address: String?,
	@Column(name = "window_start") val windowStart: LocalDateTime,
	@Column(name = "window_end") val windowEnd: LocalDateTime,
	@Enumerated(EnumType.STRING) var status: OrderStatus,
	@ManyToOne(fetch = FetchType.LAZY)
	@JoinColumn(name = "round_id")
	var round: RoundEntity?,
	@Column(name = "created_at") val createdAt: Instant,
) {
	override fun equals(other: Any?) = other is OrderEntity && other.id == id
	override fun hashCode() = id.hashCode()
	override fun toString() = "OrderEntity(id=$id, status=$status)"
}

@Entity
@Table(name = "round")
class RoundEntity(
	@Id val id: UUID,
	@Column(name = "planned_at") val plannedAt: Instant,
	@Column(name = "distance_m") val distanceMeters: Double,
	@Column(name = "duration_s") val durationSeconds: Double,
	val cost: BigDecimal,
	@Column(name = "price_per_km") val pricePerKm: BigDecimal,
	@Column(name = "radius_m") val radiusMeters: Double,

	@ElementCollection(fetch = FetchType.EAGER)
	@CollectionTable(name = "round_stop", joinColumns = [JoinColumn(name = "round_id")])
	@OrderColumn(name = "seq")
	val stops: MutableList<RoundStopEmbeddable> = mutableListOf(),

	@ElementCollection(fetch = FetchType.EAGER)
	@CollectionTable(name = "round_share", joinColumns = [JoinColumn(name = "round_id")])
	@MapKeyColumn(name = "merchant_id")
	@Column(name = "amount")
	val shares: MutableMap<UUID, BigDecimal> = mutableMapOf(),
) {
	override fun equals(other: Any?) = other is RoundEntity && other.id == id
	override fun hashCode() = id.hashCode()
	override fun toString() = "RoundEntity(id=$id, distanceMeters=$distanceMeters, cost=$cost)"
}

/** One stop of a round's route; its position in the list is stored in `seq`. */
@Embeddable
class RoundStopEmbeddable(
	@Enumerated(EnumType.STRING) val kind: StopKind,
	@Column(name = "merchant_id") val merchantId: UUID,
	@Column(name = "order_id") val orderId: UUID?,
	val lon: Double,
	val lat: Double,
)
